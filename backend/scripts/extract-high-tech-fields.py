"""Generate the searchable catalog from the supplied Word document, not its TOC."""
import hashlib
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET
import zipfile


def extract(source):
    ns = {"w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main"}
    w = "{" + ns["w"] + "}"
    with zipfile.ZipFile(source) as archive:
        numbering = ET.fromstring(archive.read("word/numbering.xml"))
        abstracts = {node.get(w + "abstractNumId"): node for node in numbering.findall("w:abstractNum", ns)}
        numbers = {node.get(w + "numId"): abstracts[node.find("w:abstractNumId", ns).get(w + "val")]
                   for node in numbering.findall("w:num", ns)}
        paragraphs = ET.fromstring(archive.read("word/document.xml")).findall("w:body/w:p", ns)
    counters = {}
    groups = []
    first = second = None
    group = None
    active = False
    for paragraph in paragraphs:
        text = "".join(node.text or "" for node in paragraph.findall(".//w:t", ns)).strip()
        if not text:
            continue
        num = paragraph.find("w:pPr/w:numPr", ns)
        if num is not None:
            num_id = num.find("w:numId", ns).get(w + "val")
            level = num.find("w:ilvl", ns).get(w + "val")
            definition = numbers[num_id].find(f"w:lvl[@w:ilvl='{level}']", ns)
            fmt = definition.find("w:numFmt", ns).get(w + "val")
            if fmt != "chineseCounting":
                raise ValueError(f"Unsupported heading numbering: {fmt}")
            key = (num_id, level)
            count = counters.get(key, int(definition.find("w:start", ns).get(w + "val")))
            counters[key] = count + 1
            assert 1 <= count <= 9
            prefix = definition.find("w:lvlText", ns).get(w + "val").replace("%1", "一二三四五六七八九"[count - 1])
            text = prefix + text
        # The TOC has page numbers; only body heading styles start the catalog.
        style = paragraph.find("w:pPr/w:pStyle", ns)
        if re.match(r"^[一二三四五六七八九十]+、", text) and (active or (style is not None and style.get(w + "val") == "2")):
            active = True
            first, second, group = text, None, None
        elif not active:
            continue
        elif re.match(r"^[（(][一二三四五六七八九十]+[）)]", text):
            second, group = text, None
        elif re.match(r"^\d+\s*[.．、]", text):
            assert first and second, text
            group = {"id": f"g{len(groups) + 1:03}", "path": [first, second, text], "description": [], "exclusions": [], "fields": []}
            groups.append(group)
        elif group is not None:
            if text.startswith("*"):
                group["exclusions"].append(text)
                continue
            group["description"].append(text)
            # Semicolons delimit source technologies; commas and slashes belong to terms.
            clauses, buffer, depth = [], [], 0
            for char in text:
                if char in "（(":
                    depth += 1
                elif char in "）)":
                    depth = max(0, depth - 1)
                if char in "；;" and depth == 0:
                    clauses.append("".join(buffer))
                    buffer = []
                else:
                    buffer.append(char)
            clauses.append("".join(buffer))
            for clause in clauses:
                leaf = clause.strip().rstrip("。；;")
                if leaf.endswith("等"):
                    leaf = leaf[:-1]
                if not leaf:
                    continue
                label = " / ".join([*group["path"], leaf])
                assert len(label) <= 512, label
                if any(field["label"] == label for field in group["fields"]):
                    continue
                group["fields"].append({"id": f'{group["id"]}-{len(group["fields"]) + 1:03}', "label": label})
    assert len(groups) == 254, len(groups)
    assert len({group["path"][0] for group in groups}) == 8
    assert len({tuple(group["path"][:2]) for group in groups}) == 49
    assert all(group["fields"] for group in groups)
    example = "一、电子信息 / （一）软件 / 9. 企业管理软件 / 数据分析与决策支持的商业智能（BI）软件"
    assert any(field["label"] == example for group in groups for field in group["fields"])
    return groups


if __name__ == "__main__":
    source = Path(sys.argv[1])
    destination = Path(__file__).resolve().parents[1] / "src/modules/client/high-tech/high-tech-full-field-catalog.ts"
    groups = extract(source)
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    destination.write_text(
        "// Generated by scripts/extract-high-tech-fields.py from 国家重点支持的高新技术领域.docx.\n"
        f"// Source SHA256: {digest}\n"
        "// Level four contains source prose clauses, not separately numbered official headings.\n"
        "export interface HighTechField { id: string; label: string }\n"
        "export interface HighTechFieldGroup { id: string; path: string[]; description: string[]; exclusions: string[]; fields: HighTechField[] }\n"
        "export const HIGH_TECH_FULL_FIELD_CATALOG: HighTechFieldGroup[] = "
        + json.dumps(groups, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"Generated {len(groups)} categories / {sum(len(g['fields']) for g in groups)} fields; max label length {max(len(f['label']) for g in groups for f in g['fields'])}")
