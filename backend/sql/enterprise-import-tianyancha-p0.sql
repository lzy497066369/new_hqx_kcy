INSERT INTO `biz_enterprise_basic_info` (
  `enterprise_id`,
  `name`,
  `credit_code`,
  `legal_person_name`,
  `industry`,
  `company_org_type`,
  `province`,
  `city`,
  `district`,
  `reg_location`,
  `phone_number`,
  `email`,
  `created_at`,
  `updated_at`
)
SELECT
  e.`id`,
  e.`name`,
  e.`credit_code`,
  e.`legal_person`,
  e.`industry`,
  e.`enterprise_type`,
  e.`province`,
  e.`city`,
  e.`district`,
  e.`address`,
  e.`contact_phone`,
  e.`contact_email`,
  e.`created_at`,
  e.`updated_at`
FROM `biz_enterprise` e
LEFT JOIN `biz_enterprise_basic_info` b ON b.`enterprise_id` = e.`id`
WHERE b.`id` IS NULL;
